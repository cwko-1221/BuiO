// Subject names arrive from imported spreadsheets, so a name with no mapping is
// shown exactly as the school wrote it.
window.subjectLabel = BuiI18n.subjectLabel = function (name) {
  const key = 'r.subj.' + String(name || '').trim();
  const translated = BuiI18n.t(key);
  return translated === key ? name : translated;
};
