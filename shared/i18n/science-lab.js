// A few labels are built at runtime, so they are matched by shape.
const SCENE_PATTERNS = [
  [/^萬字夾 (\d+)$/, 'Paper clip $1'],
  [/^室溫 (.+) °C · 氣球 (.+) mL$/, 'Room $1 °C · balloon $2 mL'],
  [/^水溫 (.+) °C · 氣球 (.+) mL$/, 'Water $1 °C · balloon $2 mL'],
  [/^(.+) 分鐘$/, '$1 min'],
];

BuiI18n.sceneLabel = function (text) {
  if (BuiI18n.lang !== 'en-US' || typeof text !== 'string' || !text) return text;
  const exact = SCENE_LABELS[text];
  if (exact) return exact;
  for (const [pattern, replacement] of SCENE_PATTERNS) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return text;
};
