import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { ASSETS, assetLedger } from '../game-app/public/js/v2/assets.js';

const root = process.cwd();
const propsDir = path.join(root,'game-app','public','images','v2','props');
const dataDir = path.join(root,'game-app','public','images','v2','data');
const indexFile = path.join(root,'game-app','public','js','v2','available-assets.js');
fs.mkdirSync(propsDir,{recursive:true}); fs.mkdirSync(dataDir,{recursive:true});

const proceduralFile = path.join(dataDir,'procedural-assets.json');
const procedural = new Set(fs.existsSync(proceduralFile) ? JSON.parse(fs.readFileSync(proceduralFile,'utf8')) : []);
const hash = value => [...value].reduce((n,ch)=>Math.imul(n ^ ch.charCodeAt(0),16777619)>>>0,2166136261);
const pointsFor = (type,w,h,seed) => {
  const skew = (seed % 13) - 6;
  if (type === 'trapezoid') return `${w*.08},${h*.78} ${w*.2+skew},${h*.13} ${w*.78},${h*.08} ${w*.94},${h*.75}`;
  if (type === 'polygon' || type === 'compound') return `${w*.06},${h*.72} ${w*.12},${h*.3} ${w*.34},${h*.07} ${w*.72},${h*.12} ${w*.94},${h*.5} ${w*.82},${h*.83}`;
  return `${w*.06},${h*.76} ${w*.1},${h*.24} ${w*.9},${h*.2} ${w*.94},${h*.76}`;
};
const proceduralSvg = asset => {
  const w=512,h=512, seed=hash(asset.id), [base,dark,light]=asset.palette;
  const shape = asset.body.type === 'circle'
    ? `<ellipse cx="256" cy="270" rx="190" ry="${150 + seed%35}"/>`
    : `<polygon points="${pointsFor(asset.body.type,w,h,seed)}"/>`;
  const accents = Array.from({length:3 + seed%3},(_,i)=>{
    const x=115+((seed>>(i*3))%282), y=135+((seed>>(i*4+2))%235), r=18+((seed>>(i+6))%28);
    return `<circle cx="${x}" cy="${y}" r="${r}" fill="${i%2?light:dark}" opacity=".78" stroke="#293149" stroke-width="9"/>`;
  }).join('');
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
    <g stroke="#293149" stroke-width="20" stroke-linejoin="round" stroke-linecap="round" fill="${base}">${shape}</g>
    <path d="M105 340 Q250 ${250-seed%45} 407 315" fill="none" stroke="${dark}" stroke-width="20" opacity=".8"/>
    <path d="M128 175 Q245 92 365 155" fill="none" stroke="${light}" stroke-width="22" opacity=".9"/>
    ${accents}
  </svg>`);
};

for (const asset of ASSETS) {
  const file=path.join(propsDir,`${asset.id}.webp`);
  if (fs.existsSync(file)) continue;
  await sharp(proceduralSvg(asset)).resize(512,512,{fit:'contain'}).webp({quality:88,alphaQuality:95}).toFile(file);
  procedural.add(asset.id);
}
fs.writeFileSync(proceduralFile,JSON.stringify([...procedural].sort(),null,2));

const available = ASSETS.filter(a=>fs.existsSync(path.join(propsDir,`${a.id}.webp`))).map(a=>a.id).sort();
fs.writeFileSync(indexFile,`// Generated by npm run build:game-assets.\nexport const AVAILABLE_ASSETS = ${JSON.stringify(available,null,2)};\n`);

const ledger = assetLedger();
ledger.promptTemplate = {
  useCase:'stylized-concept', background:'#ff00ff', outline:'thick dark navy', light:'upper-left',
  constraints:['single isolated object','complete silhouette','no cast shadow','no text','no logo','original design']
};
ledger.availableCount = available.length;
ledger.imagegenCount = available.length - procedural.size;
ledger.proceduralCount = procedural.size;
ledger.assets = ledger.assets.map(a=>({...a,available:available.includes(a.id),source:procedural.has(a.id)?'procedural-master':'imagegen-master'}));
fs.writeFileSync(path.join(dataDir,'asset-ledger.json'),JSON.stringify(ledger,null,2));
console.log(`Game asset index built: ${available.length}/${ASSETS.length} shipping prop images (${ledger.imagegenCount} imagegen, ${ledger.proceduralCount} procedural).`);
