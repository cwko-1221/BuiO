import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { ASSETS } from '../game-app/public/js/v2/assets.js';

const root = process.cwd();
const propsDir = path.join(root, 'game-app', 'public', 'images', 'v2', 'props');
const outputFile = path.join(root, 'game-app', 'public', 'js', 'v2', 'asset-geometry.js');

function occupiedRows(alpha, width, height, x0, x1) {
  const rows = [];
  const required = Math.max(1, Math.ceil((x1 - x0) * 0.25));
  for (let y = 0; y < height; y++) {
    let count = 0;
    for (let x = x0; x < x1; x++) if (alpha[y * width + x] >= 64) count++;
    rows.push(count >= required);
  }
  return rows;
}

function runs(rows) {
  const result = [];
  let start = -1;
  for (let y = 0; y <= rows.length; y++) {
    if (rows[y] && start < 0) start = y;
    if ((!rows[y] || y === rows.length) && start >= 0) {
      if (y - start >= 2) result.push([start, y]);
      start = -1;
    }
  }
  return result;
}

async function analyze(asset) {
  const file = path.join(propsDir, `${asset.id}.webp`);
  const { data, info } = await sharp(file)
    .ensureAlpha()
    .resize({ width: 72, height: 72, fit: 'inside', withoutEnlargement: true })
    .raw()
    .toBuffer({ resolveWithObject: true });
  const alpha = new Uint8Array(info.width * info.height);
  for (let i = 0; i < alpha.length; i++) alpha[i] = data[i * 4 + 3];

  const columns = Math.min(28, Math.max(10, Math.round(info.width / 3)));
  const parts = [];
  for (let column = 0; column < columns; column++) {
    const x0 = Math.floor(column * info.width / columns);
    const x1 = Math.max(x0 + 1, Math.floor((column + 1) * info.width / columns));
    for (const [y0, y1] of runs(occupiedRows(alpha, info.width, info.height, x0, x1))) {
      const padX = 0.001, padY = 0.003;
      parts.push({
        x: (x0 + x1) / (2 * info.width),
        y: (y0 + y1) / (2 * info.height),
        w: Math.min(1, (x1 - x0) / info.width + padX),
        h: Math.min(1, (y1 - y0) / info.height + padY)
      });
    }
  }

  return {
    source: { w: info.width, h: info.height },
    aspect: info.width / info.height,
    parts: parts.filter(part => part.w * part.h >= 0.0015)
  };
}

const geometry = {};
for (const asset of ASSETS) geometry[asset.id] = await analyze(asset);
fs.writeFileSync(outputFile, `// Generated by npm run build:game-assets.\nexport const ASSET_GEOMETRY=${JSON.stringify(geometry, null, 2)};\n`);
console.log(`Analyzed alpha geometry for ${Object.keys(geometry).length} props.`);
