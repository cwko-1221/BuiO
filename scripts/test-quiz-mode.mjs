import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { QuizRoom, pointsForAnswer } = require('../quiz-app/lib/QuizRoom');
const set = { title: 'Quiz test', questions: [
  { question: 'Image question', image: 'data:image/png;base64,aW1hZ2U=', choices: ['Red', 'Blue', 'Yellow', 'Green'], correctIndex: 1 },
  { question: 'Next question', choices: ['A', 'B', 'C', 'D'], correctIndex: 0 },
] };
assert.equal(pointsForAnswer(true, 100, 20000), 1000);
assert.equal(pointsForAnswer(true, 10000, 20000), 750);
assert.equal(pointsForAnswer(true, 20000, 20000), 500);
assert.equal(pointsForAnswer(false, 100, 20000), 0);
const room = new QuizRoom({ code: '123456', set, hostName: 'Teacher', seconds: 20, now: 0 });
assert.throws(() => room.startQuestion(0), /未有學生/);
room.join('fast', 'Fast', 0); room.join('slow', 'Slow', 1); room.join('wrong', 'Wrong', 2); room.join('absent', 'Absent', 3);
room.startQuestion(1000);
assert.equal(room.opensAt, 4000); assert.equal(room.closesAt, 24000);
assert.throws(() => room.answer('fast', room.roundId, 1, 3999), /尚未開始/);
assert.throws(() => room.answer('fast', 'stale-round', 1, 5000), /已結束/);
assert.throws(() => room.answer('fast', room.roundId, '1', 5000), /選項無效/);
assert.throws(() => room.answer('outsider', room.roundId, 1, 5000), /加入課堂/);
assert.throws(() => room.startQuestion(5000), /本題分數/);
assert.throws(() => room.showLeaderboard(), /結束本題/);
room.answer('fast', room.roundId, 1, 4100);
assert.throws(() => room.answer('fast', room.roundId, 0, 4200), /已經提交/);
room.answer('slow', room.roundId, 1, 14000);
room.answer('wrong', room.roundId, 2, 5000);
assert.equal(room.players.get('fast').score, 0, 'scores remain private until the question ends');
const student = room.playerView('fast', 5000), teacher = room.hostView(5000);
for (const key of ['question', 'choices', 'image', 'correctIndex', 'distribution', 'leaderboard']) assert.equal(student[key], undefined, `student cannot receive ${key} during a question`);
assert.equal(teacher.distribution, undefined); assert.equal(teacher.correctIndex, undefined);
assert.equal(student.me.result, undefined); assert.equal(student.me.score, 0);
assert.equal(teacher.question.image, set.questions[0].image);
room.players.get('absent').connected = false;
assert.equal(room.participants.size, 4, 'a disconnect does not make the round end early');
assert.throws(() => room.answer('absent', room.roundId, 1, room.closesAt), /時間已結束/);
room.endQuestion();
assert.deepEqual(room.hostView().distribution.map(d => d.voters.length), [0, 2, 1, 0]);
assert.equal(room.hostView().unanswered[0].name, 'Absent');
assert.equal(room.players.get('fast').score, 1000); assert.equal(room.players.get('slow').score, 750);
assert.equal(room.players.get('wrong').score, 0);
assert.equal(room.playerView('absent').me.result.choice, null);
assert.equal(room.endQuestion(), false); assert.equal(room.players.get('fast').score, 1000, 'reveal never awards points twice');
room.join('late', 'Late', 25000);
assert.equal(room.playerView('late').me.result, null, 'late joiners do not inherit another round result');
room.showLeaderboard();
assert.deepEqual(room.leaderboard().map(p => p.key), ['fast', 'slow', 'wrong', 'absent', 'late']);
room.startQuestion(30000);
const second = room.roundId;
assert.equal(room.participants.size, 4); assert.equal(room.playerView('fast').me.choice, null);
room.hostConnected = false;
assert.throws(() => room.answer('fast', second, 0, 34000), /重新連線/);
room.hostConnected = true;
room.join('absent', 'Absent', 33500);
assert.equal(room.participants.size, 5, 'rejoining during a round restores participation');
room.answer('fast', second, 0, 33500);
room.answer('slow', second, 0, 43000);
room.answer('late', second, 2, 34000);
room.finish();
assert.equal(room.phase, 'ended'); assert.equal(room.players.get('fast').correct, 2);
assert.equal(room.leaderboard().length, 5);
assert.throws(() => room.join('new', 'New'), /已經結束/);
room.join('fast', 'Fast');
assert.equal(room.playerView('fast').me.rank, 1, 'final standings survive reconnection');
console.log('Live Quiz unit checks passed: scoring, timing, duplicate/stale answers, privacy, distribution, missing answers, all-player rankings and reconnects.');
