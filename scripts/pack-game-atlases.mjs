import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { ASSETS } from '../game-app/public/js/v2/assets.js';

const root=process.cwd();
const propsDir=path.join(root,'game-app','public','images','v2','props');
const atlasDir=path.join(root,'game-app','public','images','v2','atlases');
const indexFile=path.join(root,'game-app','public','js','v2','atlas-index.js');
fs.mkdirSync(atlasDir,{recursive:true});
const available=ASSETS.filter(a=>fs.existsSync(path.join(propsDir,`${a.id}.webp`)));
const pages=[]; const index={};

for(const zone of [...new Set(available.map(a=>a.zone))]){
  const items=[];
  for(const asset of available.filter(a=>a.zone===zone)){
    const input=path.join(propsDir,`${asset.id}.webp`);
    // Atlas frames contain only painted pixels. Keeping the transparent
    // image-generation canvas made visible platforms several times smaller
    // than their authored render box and separated art from its collider.
    const buf=await sharp(input)
      .trim({background:{r:0,g:0,b:0,alpha:0}})
      .resize({width:240,height:240,fit:'inside',withoutEnlargement:true})
      .png().toBuffer();
    const meta=await sharp(buf).metadata(); items.push({asset,buf,w:meta.width,h:meta.height});
  }
  let pageNo=0,x=4,y=4,rowH=0,placed=[];
  const flush=async()=>{
    if(!placed.length)return;
    const key=`${zone}-${pageNo}`;const imageName=`${key}.webp`;const jsonName=`${key}.json`;
    await sharp({create:{width:2048,height:2048,channels:4,background:{r:0,g:0,b:0,alpha:0}}}).composite(placed.map(p=>({input:p.buf,left:p.x,top:p.y}))).webp({quality:90,alphaQuality:95}).toFile(path.join(atlasDir,imageName));
    const frames={};for(const p of placed){frames[p.asset.id]={frame:{x:p.x,y:p.y,w:p.w,h:p.h},rotated:false,trimmed:false,spriteSourceSize:{x:0,y:0,w:p.w,h:p.h},sourceSize:{w:p.w,h:p.h}};index[p.asset.id]={key:`atlas-${key}`,frame:p.asset.id};}
    fs.writeFileSync(path.join(atlasDir,jsonName),JSON.stringify({frames,meta:{app:'BuiO atlas builder',version:'2',image:imageName,format:'RGBA8888',size:{w:2048,h:2048},scale:'1'}},null,2));
    pages.push({key:`atlas-${key}`,image:`/game/images/v2/atlases/${imageName}`,json:`/game/images/v2/atlases/${jsonName}`});
    pageNo++;x=4;y=4;rowH=0;placed=[];
  };
  for(const item of items){if(x+item.w+4>2048){x=4;y+=rowH+4;rowH=0;}if(y+item.h+4>2048)await flush();placed.push({...item,x,y});x+=item.w+4;rowH=Math.max(rowH,item.h);}await flush();
}

fs.writeFileSync(indexFile,`// Generated by npm run build:game-assets.\nexport const ATLAS_PAGES=${JSON.stringify(pages,null,2)};\nexport const ATLAS_INDEX=${JSON.stringify(index,null,2)};\n`);
console.log(`Packed ${available.length} props into ${pages.length} atlas page(s).`);
