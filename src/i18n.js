export function currentLanguage() {
  return state.currentUser?.language
    || JSON.parse(localStorage.getItem('buiSettings') || '{}').language
    || 'zh-HK';
}

// vars fill {name} placeholders, so a sentence can keep its own word order in
// each language instead of being glued together from fragments.
export function t(key, vars) {
  const lang = currentLanguage();
  let text = I18N[lang]?.[key] || I18N['zh-HK'][key] || key;
  if (vars) {
    text = text.replace(/\{(\w+)\}/g, (whole, name) =>
      Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole);
  }
  return text;
}
